import type { AttackButton, Direction } from '../../input/types';

export type HitLevel = 'high' | 'mid' | 'low' | 'air' | 'throw' | 'special';

export interface MoveDefinition {
  id: string;
  input: { direction?: Direction; sequence?: readonly Direction[]; buttons: readonly AttackButton[] };
  precisionWindowFrames?: number;
  cancelOnHit?: { moveIds: readonly string[]; windowFrames: number };
  throw?: {
    range: number;
    breakButtons: readonly AttackButton[];
    breakFrames: number;
    breakRecovery: number;
    launchDistance: { forward: number; backward: number };
  };
  parryable?: boolean;
  /** Frames iniciais do startup em que o golpe ignora ataques de strike. */
  strikeInvulnerableStartupFrames?: number;
  airborne?: boolean;
  crouching?: boolean;
  startup: number;
  activeFrames: number;
  recovery: number;
  damage: number;
  hitstun: number;
  blockstun: number;
  pushback: { hit: number; block: number };
  advance?: number;
  hitLevel: HitLevel;
  hitbox: { forward: number; yOffset: number; width: number; height: number };
}

